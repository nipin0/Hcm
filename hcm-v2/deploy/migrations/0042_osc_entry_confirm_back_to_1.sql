-- 0042_osc_entry_confirm_back_to_1.sql
-- 【2026-09-15】回退 `osc.entry_confirm_bars` 2 → 1（**有实测证据**，非拍脑袋）
--
-- 背景：0041 按规格（场景2"连续 2 根 K 跌破"）把它设为 2。上线后回放实测发现
--   **它把箱体入场彻底关死**，故回退。
--
-- ── 实测（洁净窗口 2026-09-07..09-15，1923 根 M5，模型 v3；唯一变量=本键）──
--   运行  改动                          S1 占用   箱体入场(osc_at_box_lower+upper)
--   ─────────────────────────────────────────────────────────────────────
--   A     代码默认（confirm=1）            192          7
--   H     **仅 confirm=2**                198          **0**    ← 一单不开
--   I     仅 quantile（confirm=1）          106          6
--   B     生产配置（三项全开）              151          0
--   ⇒ **致死的是 confirm=2**，quantile 只让入场 7→6（保留）。
--
-- ── 根因（比"参数不对"更重要，写下来避免重犯）──────────────────────
--   边界触及**本质上是一次性插针**：价格贴着下沿收盘后，下一根就均值回归弹回箱内
--   （这正是震荡态的定义）。要求"**连续** N 根满足边界条件"与"触带即反手"的语义
--   **天然冲突**。实测 `osc_edge_wait` 只有 16~20 根，且**从未出现连续两根**。
--
--   ⚠ 口径反思：规格原文只写"满足防抖 K 线校验"，未定义"连续"还是"N 根内出现过"。
--     我实现为**连续 N 根**（更严）→ 不可达。若日后要保留防抖语义，应改为
--     "**N 根内出现过**"或"去重（同一波段只触发一次）"，而非"连续"。
--
-- ── 保留未动 ────────────────────────────────────────────────────
--   `osc.bands_mode=quantile`：入场保留（7→6），且是规格 12.1 的推荐 → **保留**。
--   `osc.break_confirm_bars=2`：它是**离场**保护（箱体突破止损），与"入场"相反 ——
--     破界后价格**持续**在外是常态（那才是突破），故"连续 2 根"在语义上是合适的，
--     且未测到有害 → **保留**。
--
-- ⚠ 写 PG 不足够：ConfigProviderV3 是 L1 → **L2(Redis)** → L3(PG)，Redis 命中即返回。
--   必须一并：redis-cli HSET hcm:config:v2 osc.entry_confirm_bars 1
--            redis-cli PUBLISH hcm:config:invalidate osc.entry_confirm_bars
--   （本次两级的**一致性**也必须核对：曾出现 shell 引号破坏导致 Redis=1 / PG=2 的分裂）

UPDATE hcm_config.metadata
   SET current_value = '1',
       description = '入场防抖根数：连续 N 根满足边界条件才开仓。'
                     '**当前=1（= 既有行为）**。2026-09-15 曾按规格设为 2，'
                     '洁净窗口回放实测**箱体入场 7→0（一单不开）**，故回退（0042）。'
                     '根因：边界触及本质是一次性插针，"连续 N 根"与触带即反手语义冲突。'
                     '⚠ 若要保留防抖，应改为"N 根内出现过"而非"连续 N 根"。',
       updated_at = now()
 WHERE config_key = 'osc.entry_confirm_bars';

