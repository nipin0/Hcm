-- 0038_state_dir_tf_back_to_m5.sql
-- 【2026-09-15】方向来源周期回退为 **M5（主周期）** —— 用户裁定（方案 §56.4）
--
-- 决策：**继续用主周期 M5 判方向**，不采用 0037 试行的 H1。
--
-- ── 用户理由（原话）────────────────────────────────────────────────
--   "M5 现判断 DOWN 侧符号全网格反向；**符合行情方向**；继续主周期 M5 方向"
--   即：模块判 DOWN 之后价格反弹（前视边际为正）**不构成"不可用"的依据** ——
--   模块判的是**当下这一段**的方向（须同时满足 斜率<0 且 −DI>+DI 才给 DOWN），
--   而"判 DOWN 后 12 根内出现反弹"正是下行腿之后的**均值回归**。
--   用"前视位移"当唯一判据，会把这种正确刻画误读成"符号反向"。
--
-- ── 本迁移同时记录"改动须知的实测事实"（不改变决策，仅备查）──────────
--   1. 方向符号**确实参与选边**，不只是否决项：
--        `resolve_trend_dir(direction, slope)` → `tdir` →
--        `_pullback_entry` 返回 UP→BUY / DOWN→SELL
--        （`state_strategy.py:746` / `:762` / `:772` 的 S2 入场路径）。
--      故方向符号会影响"做多还是做空"，读 §56 时不能只看"否决"一面。
--   2. 端到端 A/B（1922 根洁净 M5，唯一变量=本键，`require_trigger=true`）：
--
--        指标（验收口径）      dir=M5    dir=H1
--        ──────────────────────────────────────
--        漏检                    0         0
--        误报                 34.6%     28.8%
--        中位提前量            −2.0      +0.0     ← M5 **提前 2 根**
--        趋势态占用           38.1%     26.3%
--        →S2/S3 入口            31        15
--
--      ⇒ 取舍明确：**M5 提前量更好**（与"敏锐捕捉行情变化"的目标一致），
--        H1 误报更低但更慢。用户按"主周期方向"的一贯口径选 M5。
--
-- ── 纪律 ─────────────────────────────────────────────────────────
--   `default_value` 恒为 'M5'（= 代码内置行为，改代码默认属另一类变更）；
--   `current_value` 回到 'M5'。
--   **键本身保留**：它是"方向来源周期"的显式开关，保留后可随时切换而无需改代码
--   （切换是**热重载**生效，30s 内；本键不涉及代码路径，故无需重启）。
--
-- ⚠ 写 PG 不足够：`ConfigProviderV3` 是 L1(内存) → L2(Redis hcm:config:v2) → L3(PG)，
--   **Redis 命中即返回**。手工执行时须一并：
--     redis-cli HSET hcm:config:v2 state.dir.tf M5
--     redis-cli PUBLISH hcm:config:invalidate state.dir.tf

UPDATE hcm_config.metadata
   SET current_value = 'M5',
       description = '方向来源周期。**当前决策 = M5（主周期）**（用户 2026-09-15 裁定，见方案 §56.4）：'
                     'M5 判 DOWN 后的前视反弹是**均值回归**，不构成"符号反向=不可用"的依据。'
                     '实测取舍：dir=M5 时中位提前量 −2.0（提前 2 根）、误报 34.6%；'
                     'dir=H1 时误报 28.8% 但中位提前量 +0.0（更慢）。'
                     '⚠ 方向符号参与选边（UP→BUY / DOWN→SELL），不只作否决。'
                     '切换为本键**热重载**生效（30s），无需重启。',
       updated_at = now()
 WHERE config_key = 'state.dir.tf';

